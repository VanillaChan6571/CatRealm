function getInitialLanguage(): AppLanguage {
  if (typeof window === 'undefined') return detectAppLanguage();
  try {
    const raw = window.localStorage.getItem('catrealm.settings');
    if (!raw) return detectAppLanguage();
    const parsed = JSON.parse(raw) as { language?: unknown };
    return LANGUAGE_OPTIONS.includes(parsed.language as AppLanguage)
      ? (parsed.language as AppLanguage)
      : detectAppLanguage();
  } catch {
    return detectAppLanguage();
  }
}

void i18n.use(initReactI18next).init({
  resources,
  lng: getInitialLanguage(),
  fallbackLng: 'en',
  interpolation: {
    escapeValue: false,
  },
});

