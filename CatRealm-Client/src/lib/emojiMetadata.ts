export function normalizeEmojiSearchText(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').replace(/\s+/g, ' ').trim();
}

export function toEmojiSearchTerms(value: string): string[] {
  return normalizeEmojiSearchText(value).split(' ').filter(Boolean);
}

export function normalizeEmojiGlyph(emoji: string): string {
  return emoji.replace(/[\uFE0E\uFE0F]/g, '');
}

export type EmojiMetadataLookup = Map<string, { label: string; tags: string[] }>;

let emojiMetadataLookupCache: EmojiMetadataLookup | null = null;
let emojiMetadataLookupPromise: Promise<EmojiMetadataLookup> | null = null;

function buildEmojiMetadataLookup(data: EmojiMetadata[]): EmojiMetadataLookup {
  const map = new Map<string, { label: string; tags: string[] }>();
  for (const entry of data) {
    if (!entry.emoji) continue;
    const label = typeof entry.label === 'string' ? entry.label : '';
    const tags = Array.isArray(entry.tags)
      ? entry.tags.filter((tag): tag is string => typeof tag === 'string')
      : [];
    const normalized = normalizeEmojiGlyph(entry.emoji);
    map.set(entry.emoji, { label, tags });
    if (!map.has(normalized)) {
      map.set(normalized, { label, tags });
    }
  }
  return map;
}

export async function loadEmojiMetadataLookup(): Promise<EmojiMetadataLookup> {
  if (emojiMetadataLookupCache) return emojiMetadataLookupCache;
  if (!emojiMetadataLookupPromise) {
    emojiMetadataLookupPromise = import('emojibase-data/en/data.json')
      .then((mod) => buildEmojiMetadataLookup(mod.default as EmojiMetadata[]))
      .then((lookup) => {
        emojiMetadataLookupCache = lookup;
        return lookup;
      })
      .catch((error) => {
        emojiMetadataLookupPromise = null;
        throw error;
      });
  }
  return emojiMetadataLookupPromise;
}

export function getEmojiMetadataLookupCache(): EmojiMetadataLookup | null {
  return emojiMetadataLookupCache;
}
